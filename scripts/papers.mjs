// Builds src/content/docs/resources/papers.md from data/papers.json.
//
//   node scripts/papers.mjs           render the table from the stored counts
//   node scripts/papers.mjs --update  first refresh the counts from OpenAlex (needs network)
//
// Papers with an arXiv id or DOI are looked up by it; others by title and year. A paper that
// cannot be matched keeps its old count (or none). Add a paper by appending to data/papers.json.
import { readFileSync, writeFileSync } from 'node:fs';

const dataFile = new URL('../data/papers.json', import.meta.url);
const pageFile = new URL('../src/content/docs/resources/papers.md', import.meta.url);
const papers = JSON.parse(readFileSync(dataFile, 'utf8'));

const API = 'https://api.openalex.org/works';
const fields = 'select=id,title,publication_year,cited_by_count';

async function lookup(p) {
	let url;
	if (p.doi) url = `${API}/doi:${p.doi}?${fields}`;
	else if (p.arxiv) url = `${API}/doi:10.48550/arXiv.${p.arxiv}?${fields}`;
	else if (p.title)
		url = `${API}?filter=title.search:${encodeURIComponent(p.title.replace(/[,|:]/g, ' '))},publication_year:${p.year}&per-page=1&${fields}`;
	else return null;
	const res = await fetch(url);
	if (!res.ok) return null;
	const body = await res.json();
	return body.results ? (body.results[0] ?? null) : body;
}

if (process.argv.includes('--update')) {
	const today = new Date().toISOString().slice(0, 10);
	for (const p of papers) {
		try {
			const work = await lookup(p);
			if (work) {
				p.citations = work.cited_by_count;
				p.citationsDate = today;
			} else console.warn(`no match: ${p.ref}`);
		} catch (err) {
			console.warn(`failed: ${p.ref}: ${err.message}`);
		}
	}
	writeFileSync(dataFile, JSON.stringify(papers, null, 2) + '\n');
}

const order = ['review', 'experiment', 'simulation', 'theory', 'model', 'unclassified'];
const rows = [...papers].sort(
	(a, b) => order.indexOf(a.type) - order.indexOf(b.type) || b.year - a.year,
);
const dates = papers.map((p) => p.citationsDate).filter(Boolean).sort();
const asOf = dates.length ? `Counts from OpenAlex, as of ${dates.at(-1)}.` : 'Counts not yet filled in.';

const cell = (p) => {
	const text = p.title ? `${p.ref}, *${p.title}*` : p.ref;
	const link = p.summary ? ` ([summary](${p.summary}))` : '';
	return text.replace(/\|/g, '\\|') + link;
};

const md = `---
title: Paper overview
description: Every relevant paper in one table, with its type, how it is known and its citation count.
sidebar:
  order: 2
---

<!-- Generated by scripts/papers.mjs from data/papers.json. Edit the data file, not this page. -->

All papers these notes use, grouped by type. ${asOf} A dash means no count yet. The **Status**
column is the mark described in [About these notes](/about/); the same papers, grouped by topic,
are in the [bibliography](/resources/bibliography/).

| Type | Meaning |
|---|---|
| **review** | Survey of a field. |
| **experiment** | Measurements of spokes or of a discharge. |
| **simulation** | PIC, fluid or other spatially resolved numerical model. |
| **theory** | Analytic or phenomenological model. |
| **model** | Global or ionization region model (0D, volume averaged). |
| **unclassified** | Known only from a reference list; type to be checked. |

| Paper | Year | Type | Status | Citations |
|---|---|---|---|---|
${rows
	.map(
		(p) =>
			`| ${cell(p)} | ${p.year} | ${p.type}${p.note ? ` (${p.note})` : ''} | ${p.status} | ${p.citations ?? '–'} |`,
	)
	.join('\n')}
`;
writeFileSync(pageFile, md);
console.log(`wrote ${rows.length} papers`);
